"""Generate the Bangladesh location seed migration from nuhil/bangladesh-geocode (MIT).
Usage: python3 -I gen_location_seed.py <path-to-cloned-repo> <output.sql>"""
import json, sys, collections

def load(p):
    d = json.load(open(p, encoding='utf-8'))
    return next(x['data'] for x in d if x.get('type') == 'table')

def q(s):
    return "'" + s.strip().replace("'", "''") + "'"

repo, out = sys.argv[1], sys.argv[2]
div = load(f'{repo}/divisions/divisions.json')
dis = load(f'{repo}/districts/districts.json')
upa = load(f'{repo}/upazilas/upazilas.json')
uni = load(f'{repo}/unions/unions.json')

div_ids = {d['id'] for d in div}
dis_ids = {d['id'] for d in dis}
upa_ids = {u['id'] for u in upa}
assert all(d['division_id'] in div_ids for d in dis), 'orphan district'
assert all(u['district_id'] in dis_ids for u in upa), 'orphan upazila'
assert all(u['upazilla_id'] in upa_ids for u in uni), 'orphan union'

def dedupe(rows, key_fn, label):
    seen = collections.Counter(); res = []
    for r in rows:
        k = key_fn(r); seen[k] += 1
        if seen[k] > 1:
            r = dict(r); r['name'] = f"{r['name']} ({seen[k]})"
            print(f'WARN duplicate {label}: {k} -> renamed {r["name"]}', file=sys.stderr)
        res.append(r)
    return res

upa = dedupe(upa, lambda r: (r['district_id'], r['name'].strip()), 'upazila')
uni = dedupe(uni, lambda r: (r['upazilla_id'], r['name'].strip()), 'union')
for r in div + dis + upa + uni:
    assert r['name'].strip() and r['bn_name'].strip(), f'empty name: {r}'

L = ['-- Step 2.1: Bangladesh locations seed (generated by scripts/gen_location_seed.py)',
     '-- Source: github.com/nuhil/bangladesh-geocode (MIT). Counts: '
     f'{len(div)} divisions, {len(dis)} districts, {len(upa)} upazilas, {len(uni)} unions.',
     '-- Source ids are preserved so references stay stable.', '']
L.append('insert into public.divisions (id, name_en, name_bn) overriding system value values')
L.append(',\n'.join(f"({d['id']}, {q(d['name'])}, {q(d['bn_name'])})" for d in div) + ';\n')
L.append('insert into public.districts (id, division_id, name_en, name_bn, centroid) overriding system value values')
L.append(',\n'.join(
    f"({d['id']}, {d['division_id']}, {q(d['name'])}, {q(d['bn_name'])}, "
    f"st_setsrid(st_makepoint({float(d['lon'])}, {float(d['lat'])}), 4326)::geography)" for d in dis) + ';\n')
L.append('insert into public.upazilas (id, district_id, name_en, name_bn) overriding system value values')
L.append(',\n'.join(f"({u['id']}, {u['district_id']}, {q(u['name'])}, {q(u['bn_name'])})" for u in upa) + ';\n')
L.append('insert into public.unions (id, upazila_id, name_en, name_bn) overriding system value values')
L.append(',\n'.join(f"({u['id']}, {u['upazilla_id']}, {q(u['name'])}, {q(u['bn_name'])})" for u in uni) + ';\n')
for t in ['divisions', 'districts', 'upazilas', 'unions']:
    L.append(f"select setval(pg_get_serial_sequence('public.{t}', 'id'), (select max(id) from public.{t}));")
open(out, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print(len(div), len(dis), len(upa), len(uni))
